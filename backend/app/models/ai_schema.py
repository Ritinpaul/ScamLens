from enum import Enum
from pydantic import BaseModel, Field

class AiVerdict(str, Enum):
    SCAM = "scam"
    SUSPICIOUS = "suspicious"
    LIKELY_LEGITIMATE = "likely_legitimate"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"

class TacticItem(BaseModel):
    type: str = Field(description="The manipulation tactic (e.g. artificial_urgency, fear_threat, authority_impersonation, lottery_bait)")
    evidence: str = Field(description="Direct snippet or textual reason from the message supporting this tactic")

class AiAnalysisOutput(BaseModel):
    source: str = Field(default="model", description="Identifier marking this block as AI-derived interpretation")
    model_name: str = Field(default="llama3:latest", description="Name of the open-source model that generated this analysis")
    verdict: AiVerdict = Field(description="Preliminary semantic verdict from the model")
    summary: str = Field(description="Plain-English explanation of what the message is attempting to achieve")
    tactics: list[TacticItem] = Field(default_factory=list, description="Manipulation or social engineering tactics identified")
    requests: list[str] = Field(default_factory=list, description="Specific actions requested of the victim")
    entities: list[str] = Field(default_factory=list, description="Organizations, banks, or brands claimed to be involved")
    urls: list[str] = Field(default_factory=list, description="URLs or domains extracted by the model")
    recommended_action: str = Field(description="Direct recommendation generated by the model")
    uncertainty_reason: str = Field(default="", description="Honest statement of what information was ambiguous or missing")
    confidence_label: str = Field(
        default="model_unvalidated",
        description="Explicit notice that model confidence is qualitative and uncalibrated"
    )
    # Structured contextual calibration fields
    requests_secret_disclosure: bool = Field(
        default=False,
        description="Whether the sender asks the recipient to disclose secrets, OTP, PIN, password, or CVV"
    )
    requests_payment: bool = Field(
        default=False,
        description="Whether the sender asks the recipient to transfer money, scan payment QR, or pay fees"
    )
    requests_external_action: bool = Field(
        default=False,
        description="Whether the user is directed to click external links, call unknown numbers, or install APKs"
    )
    contains_negative_security_warning: bool = Field(
        default=False,
        description="Explicit warning advising NOT to share OTP/password, or to report fraud (reduces scam likelihood)"
    )
    contains_transaction_notification: bool = Field(
        default=False,
        description="Routine transactional debit/credit notice or account status update with no dangerous call to action"
    )
    contains_normal_due_date_language: bool = Field(
        default=False,
        description="Standard due date or promotional timeline without threats of imminent punitive disconnection/arrest"
    )
    impersonates_authority: bool = Field(
        default=False,
        description="Falsely claiming authority of banks, police, utility boards, or couriers to coerce the recipient"
    )
    uses_coercive_urgency: bool = Field(
        default=False,
        description="Threatening imminent account freeze, power shutoff, or arrest to prevent reflection"
    )
